//! The identity probe: reading the code, severity, category, kinds, and type
//! name of a generated error seen only as `&dyn Error`.
//!
//! Generated code implements the stable (deprecated for callers)
//! `Error::description` to return a fixed string built at compile time. The
//! format, frozen at 1.0 (`docs/GENERATED-CODE.md`, `tests/golden/probe.txt`):
//!
//! ```text
//! offset  length  content
//! 0       4       magic: NUL 'D' 'E' '1'
//! 4       16      the code's full value (with width) in lowercase hex, or 16 'x'
//! 20      2       severity in lowercase hex (01-18)
//! 22      2       category gRPC number in lowercase hex (01-10)
//! 24      16      kinds bits in lowercase hex
//! 40      2       flags in lowercase hex: bit 0 public message, bit 1 transparent
//! 42      1       '|'
//! 43      1-128   type name, ASCII
//! ```

use core::error::Error;

use crate::{Category, Code, Kinds, Severity};

/// The magic bytes every probe starts with.
pub(crate) const MAGIC: &[u8; 4] = b"\0DE1";
/// The length of the fixed part, before the type name.
pub(crate) const HEADER: usize = 43;
/// The longest type name a probe carries.
pub(crate) const MAX_NAME: usize = 128;

/// What a probe says about an error.
///
/// `type_name` borrows from the error (a probe from a foreign type could be
/// non-`'static`); copy it to keep it.
///
/// # Examples
///
/// ```
/// use define_err::{define_errors, identify, Category};
///
/// define_errors! {
///     namespace = "DB";
///     pub enum DbError {
///         #[code(1, help = "Raise pool.size.")]
///         #[category(DeadlineExceeded)]
///         Timeout => "query timed out",
///     }
/// }
///
/// let boxed: Box<dyn std::error::Error + Send + Sync> = Box::new(DbError::Timeout);
/// let id = identify(&*boxed).unwrap();
/// assert_eq!(id.code.unwrap().to_string(), "DB-0001");
/// assert_eq!(id.category, Category::DeadlineExceeded);
/// assert_eq!(id.type_name, "DbError::Timeout");
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct Identity<'a> {
    /// The code, if the variant has one.
    pub code: Option<Code>,
    /// The variant's severity.
    pub severity: Severity,
    /// The variant's category.
    pub category: Category,
    /// The variant's kinds.
    pub kinds: Kinds,
    /// Whether the variant wrote its own public message (otherwise the
    /// category's default applies).
    pub has_public: bool,
    /// Whether this is a transparent wrapper whose inner value has no probe.
    pub transparent: bool,
    /// `"Type::Variant"`, or `"Type"` for a struct.
    pub type_name: &'a str,
}

/// Reads the identity of an error generated by `define_errors!` or the
/// attribute front end; `None` for any other error.
///
/// A foreign error is rejected after one comparison of four bytes. Every
/// field is validated (code layout, severity range, category range, ASCII
/// name); a malformed probe is `None`. No allocation [est. about 10 ns for a
/// generated type, about 2 ns for a foreign one]. Codes identify an error;
/// they do not authenticate it.
///
/// # Examples
///
/// ```
/// use define_err::identify;
///
/// let foreign = std::fmt::Error;
/// assert!(identify(&foreign).is_none());
/// ```
#[must_use]
pub fn identify<'a>(error: &'a (dyn Error + 'static)) -> Option<Identity<'a>> {
    #[allow(deprecated)]
    let text = error.description();
    decode(text)
}

/// Walks `source()` from `error` and returns the last (innermost) entry that
/// has a code, with its identity. Stops after 64 steps, so a cyclic chain
/// cannot loop.
///
/// # Examples
///
/// ```
/// use define_err::{define_errors, innermost_code};
///
/// define_errors! {
///     namespace = "DB";
///     pub enum DbError {
///         #[code(2, help = "Restore the page.")]
///         Corrupt => "page failed its checksum",
///     }
///
///     pub enum AppError {
///         Store(#[from] inner: DbError) => "storage failed",
///     }
/// }
///
/// let err = AppError::from(DbError::Corrupt);
/// let (code, id) = innermost_code(&err).unwrap();
/// assert_eq!(code.to_string(), "DB-0002");
/// assert_eq!(id.type_name, "DbError::Corrupt");
/// ```
#[must_use]
pub fn innermost_code<'a>(error: &'a (dyn Error + 'static)) -> Option<(Code, Identity<'a>)> {
    let mut found = None;
    let mut next = Some(error);
    let mut steps = 0;
    while let Some(current) = next {
        if steps == 64 {
            break;
        }
        if let Some(identity) = identify(current) {
            if let Some(code) = identity.code {
                found = Some((code, identity));
            }
        }
        next = current.source();
        steps += 1;
    }
    found
}

/// The value of one lowercase hex digit.
const fn hex_digit(byte: u8) -> Option<u64> {
    match byte {
        b'0'..=b'9' => Some((byte - b'0') as u64),
        b'a'..=b'f' => Some((byte - b'a') as u64 + 10),
        _ => None,
    }
}

/// Lowercase hex, exactly `bytes.len()` digits, most significant first.
fn hex(bytes: &[u8]) -> Option<u64> {
    bytes
        .iter()
        .try_fold(0_u64, |value, &byte| Some(value << 4 | hex_digit(byte)?))
}

/// Decodes a probe string; `None` unless every field is valid.
pub(crate) fn decode(text: &str) -> Option<Identity<'_>> {
    let bytes = text.as_bytes();
    if bytes.len() <= HEADER || bytes.len() > HEADER + MAX_NAME || &bytes[..4] != MAGIC {
        return None;
    }
    let code = match &bytes[4..20] {
        b"xxxxxxxxxxxxxxxx" => None,
        digits => Some(Code::from_u64(hex(digits)?)?),
    };
    let severity = Severity::new(u8::try_from(hex(&bytes[20..22])?).ok()?)?;
    let category = Category::from_grpc(u8::try_from(hex(&bytes[22..24])?).ok()?)?;
    let kinds = Kinds::from_bits(hex(&bytes[24..40])?);
    let flags = hex(&bytes[40..42])?;
    if flags > 0b11 || bytes[42] != b'|' {
        return None;
    }
    let name = &bytes[HEADER..];
    if !name.iter().all(u8::is_ascii_graphic) {
        return None;
    }
    Some(Identity {
        code,
        severity,
        category,
        kinds,
        has_public: flags & 1 != 0,
        transparent: flags & 2 != 0,
        type_name: &text[HEADER..],
    })
}

#[cfg(test)]
mod tests {
    use super::decode;
    use crate::{Category, Kinds, Severity};

    #[test]
    fn test_decode_golden_probes() {
        let id = decode("\0DE13b34a2f2600000011104000000000000000101|DbError::Timeout").unwrap();
        assert_eq!(id.code.map(|c| c.number()), Some(1));
        assert_eq!(id.severity, Severity::ERROR);
        assert_eq!(id.category, Category::DeadlineExceeded);
        assert_eq!(id.kinds, Kinds::ERROR);
        assert!(id.has_public && !id.transparent);
        assert_eq!(id.type_name, "DbError::Timeout");

        let plain =
            decode("\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|PageError::NotFound").unwrap();
        assert!(plain.code.is_none());
        assert_eq!(plain.category, Category::Unknown);
    }

    #[test]
    fn test_decode_rejects_malformed_probes() {
        let good = "\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|T";
        assert!(decode(good).is_some());
        let cases = [
            "",
            "\0DE1",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|",
            "\0DE2xxxxxxxxxxxxxxxx1102000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxg1102000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx0002000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx1900000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx1100000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx1111000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000104|T",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000100:T",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|T T",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|T\n",
            "\0DE1xxxxxxxxxxxxxxxX1102000000000000000100|T",
            "\0DE13b34a2f2610000011102000000000000000100|T",
            "\0DE10000000000000000011102000000000000000100|T",
        ];
        for case in cases {
            assert!(decode(case).is_none(), "{case:?}");
        }
    }

    #[test]
    fn test_decode_name_length_limit() {
        let mut probe = std::string::String::from("\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|");
        probe.push_str(&"N".repeat(128));
        assert!(decode(&probe).is_some());
        probe.push('N');
        assert!(decode(&probe).is_none());
    }

    extern crate std;
}
