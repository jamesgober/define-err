//! The identity probe: reading the code, severity, category, kinds, and type
//! name of a generated error seen only as `&dyn Error`.
//!
//! Generated code implements the stable (deprecated for callers)
//! `Error::description` to return a fixed string built at compile time. The
//! format, frozen at 1.0 (`docs/GENERATED-CODE.md`, `tests/golden/probe.txt`):
//!
//! ```text
//! offset  length  content
//! 0       4       magic: NUL 'D' 'E' '1'
//! 4       16      the code's full value (with width) in lowercase hex, or 16 'x'
//! 20      2       severity in lowercase hex (01-18)
//! 22      2       category gRPC number in lowercase hex (01-10)
//! 24      16      kinds bits in lowercase hex
//! 40      2       flags in lowercase hex: bit 0 public message, bit 1 transparent
//! 42      1       '|'
//! 43      1-128   type name, ASCII
//! then, only when flag bit 0 is set:
//!         1       '|'
//!         0-512   the public message, UTF-8
//! ```

use core::error::Error;

use crate::{Category, Code, Kinds, Severity};

/// The magic bytes every probe starts with.
pub(crate) const MAGIC: &[u8; 4] = b"\0DE1";
/// The length of the fixed part, before the type name.
pub(crate) const HEADER: usize = 43;
/// The longest type name a probe carries.
pub(crate) const MAX_NAME: usize = 128;
/// The longest public message a probe carries.
pub(crate) const MAX_PUBLIC: usize = 512;

/// What a probe says about an error.
///
/// `type_name` borrows from the error (a probe from a foreign type could be
/// non-`'static`); copy it to keep it.
///
/// # Examples
///
/// ```
/// use define_err::{define_errors, identify, Category};
///
/// define_errors! {
///     namespace = "DB";
///     pub enum DbError {
///         #[code(1, help = "Raise pool.size.")]
///         #[category(DeadlineExceeded)]
///         Timeout => "query timed out",
///     }
/// }
///
/// let boxed: Box<dyn std::error::Error + Send + Sync> = Box::new(DbError::Timeout);
/// let id = identify(&*boxed).unwrap();
/// assert_eq!(id.code.unwrap().to_string(), "DB-0001");
/// assert_eq!(id.category, Category::DeadlineExceeded);
/// assert_eq!(id.type_name, "DbError::Timeout");
/// ```
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[non_exhaustive]
pub struct Identity<'a> {
    /// The code, if the variant has one.
    pub code: Option<Code>,
    /// The variant's severity.
    pub severity: Severity,
    /// The variant's category.
    pub category: Category,
    /// The variant's kinds.
    pub kinds: Kinds,
    /// Whether the variant wrote its own public message (otherwise the
    /// category's default applies).
    pub has_public: bool,
    /// The variant's own `#[public]` message, if it wrote one.
    pub public: Option<&'a str>,
    /// Whether this is a transparent wrapper whose inner value has no probe.
    pub transparent: bool,
    /// `"Type::Variant"`, or `"Type"` for a struct.
    pub type_name: &'a str,
}

/// Reads the identity of an error generated by `define_errors!` or the
/// attribute front end; `None` for any other error.
///
/// A foreign error is rejected after one comparison of four bytes. Every
/// field is validated (code layout, severity range, category range, ASCII
/// name); a malformed probe is `None`. No allocation; about 26 ns for a
/// generated type and 2 ns for a foreign one (`docs/PERFORMANCE.md`). Codes
/// identify an error; they do not authenticate it.
///
/// # Examples
///
/// ```
/// use define_err::identify;
///
/// let foreign = std::fmt::Error;
/// assert!(identify(&foreign).is_none());
/// ```
#[must_use]
#[inline]
pub fn identify<'a>(error: &'a (dyn Error + 'static)) -> Option<Identity<'a>> {
    #[allow(deprecated)]
    let text = error.description();
    decode(text)
}

/// What the facade and `ErrorRecord` use of an error held as `&dyn Error`.
#[derive(Clone, Copy, Debug)]
pub(crate) struct Facts<'a> {
    pub(crate) code: Option<Code>,
    pub(crate) severity: Severity,
    pub(crate) category: Category,
    pub(crate) kinds: Kinds,
    pub(crate) type_name: Option<&'a str>,
    #[cfg_attr(not(feature = "alloc"), allow(dead_code))]
    pub(crate) public: Option<&'a str>,
}

/// The facts of `error`: from its probe; a foreign error is `ERROR` with
/// category `Unknown`, except a `std::io::Error`, the one built-in fallback.
pub(crate) fn facts<'a>(error: &'a (dyn Error + 'static)) -> Facts<'a> {
    if let Some(identity) = identify(error) {
        return Facts {
            code: identity.code,
            severity: identity.severity,
            category: identity.category,
            kinds: identity.kinds,
            type_name: Some(identity.type_name),
            public: identity.public,
        };
    }
    #[cfg(feature = "std")]
    if let Some(io) = error.downcast_ref::<std::io::Error>() {
        use crate::ErrorInfo;
        return Facts {
            code: None,
            severity: Severity::ERROR,
            category: io.category(),
            kinds: io.kinds(),
            type_name: Some(io.type_name()),
            public: None,
        };
    }
    Facts {
        code: None,
        severity: Severity::ERROR,
        category: Category::Unknown,
        kinds: Kinds::ERROR,
        type_name: None,
        public: None,
    }
}

/// Walks `source()` from `error` and returns the last (innermost) entry that
/// has a code, with its identity. Stops after 64 steps, so a cyclic chain
/// cannot loop.
///
/// # Examples
///
/// ```
/// use define_err::{define_errors, innermost_code};
///
/// define_errors! {
///     namespace = "DB";
///     pub enum DbError {
///         #[code(2, help = "Restore the page.")]
///         Corrupt => "page failed its checksum",
///     }
///
///     pub enum AppError {
///         Store(#[from] inner: DbError) => "storage failed",
///     }
/// }
///
/// let err = AppError::from(DbError::Corrupt);
/// let (code, id) = innermost_code(&err).unwrap();
/// assert_eq!(code.to_string(), "DB-0002");
/// assert_eq!(id.type_name, "DbError::Corrupt");
/// ```
#[must_use]
pub fn innermost_code<'a>(error: &'a (dyn Error + 'static)) -> Option<(Code, Identity<'a>)> {
    let mut found = None;
    let mut next = Some(error);
    let mut steps = 0;
    while let Some(current) = next {
        if steps == 64 {
            break;
        }
        if let Some(identity) = identify(current) {
            if let Some(code) = identity.code {
                found = Some((code, identity));
            }
        }
        next = current.source();
        steps += 1;
    }
    found
}

/// Each byte's value as a lowercase hex digit, or a value with high bits set.
const HEX: [u8; 256] = {
    let mut table = [0xFF; 256];
    let mut byte = 0;
    while byte < 256 {
        table[byte] = match byte as u8 {
            digit @ b'0'..=b'9' => digit - b'0',
            digit @ b'a'..=b'f' => digit - b'a' + 10,
            _ => 0xFF,
        };
        byte += 1;
    }
    table
};

/// Lowercase hex, exactly `bytes.len()` digits, most significant first. No
/// branch per digit: a bad digit shows in `seen` at the end.
#[inline]
fn hex(bytes: &[u8]) -> Option<u64> {
    let (mut value, mut seen) = (0_u64, 0_u8);
    for &byte in bytes {
        let digit = HEX[usize::from(byte)];
        seen |= digit;
        value = value << 4 | u64::from(digit);
    }
    (seen < 16).then_some(value)
}

/// Eight lowercase hex digits at once, most significant first; `None` unless
/// every byte is one. Each addition below puts a byte's position against one
/// bound into its high bit. A byte at or above 0x80 could carry into its
/// neighbour, but such a byte fails the check by itself.
#[inline]
fn hex8(chunk: &[u8; 8]) -> Option<u64> {
    const ONES: u64 = 0x0101_0101_0101_0101;
    const HIGH: u64 = ONES * 0x80;
    let word = u64::from_be_bytes(*chunk);
    let from_0 = word.wrapping_add(ONES * (0x80 - 0x30));
    let past_9 = word.wrapping_add(ONES * (0x80 - 0x3a));
    let from_a = word.wrapping_add(ONES * (0x80 - 0x61));
    let past_f = word.wrapping_add(ONES * (0x80 - 0x67));
    if ((from_0 & !past_9) | (from_a & !past_f)) & !word & HIGH != HIGH {
        return None;
    }
    let nibbles = (word & (ONES * 0x0f)) + ((word >> 6) & ONES) * 9;
    let bytes = (nibbles | nibbles >> 4) & 0x00ff_00ff_00ff_00ff;
    let halves = (bytes | bytes >> 8) & 0x0000_ffff_0000_ffff;
    Some((halves | halves >> 16) & 0xffff_ffff)
}

/// Sixteen lowercase hex digits.
#[inline]
fn hex16(bytes: &[u8]) -> Option<u64> {
    let (high, low) = bytes.split_first_chunk::<8>()?;
    Some(hex8(high)? << 32 | hex8(low.first_chunk::<8>()?)?)
}

/// The severity a probe states, from its two digits alone: what dropping an
/// event below the minimum needs. `None` for anything without the magic, and
/// for a severity that does not parse, so those take the full decode.
#[inline]
pub(crate) fn stated_severity(error: &(dyn Error + 'static)) -> Option<u8> {
    #[allow(deprecated)]
    let bytes = error.description().as_bytes();
    if bytes.first_chunk::<4>() != Some(MAGIC) {
        return None;
    }
    u8::try_from(hex(bytes.get(20..22)?)?).ok()
}

/// Decodes a probe string; `None` unless every field is valid. A foreign
/// error stops at the magic.
#[inline]
pub(crate) fn decode(text: &str) -> Option<Identity<'_>> {
    if text.as_bytes().first_chunk::<4>() == Some(MAGIC) {
        decode_fields(text)
    } else {
        None
    }
}

fn decode_fields(text: &str) -> Option<Identity<'_>> {
    let bytes = text.as_bytes();
    if bytes.len() <= HEADER || bytes.len() > HEADER + MAX_NAME + 1 + MAX_PUBLIC {
        return None;
    }
    let code = match &bytes[4..20] {
        b"xxxxxxxxxxxxxxxx" => None,
        digits => Some(Code::from_u64(hex16(digits)?)?),
    };
    let severity = Severity::new(u8::try_from(hex(&bytes[20..22])?).ok()?)?;
    let category = Category::from_grpc(u8::try_from(hex(&bytes[22..24])?).ok()?)?;
    let kinds = Kinds::from_bits(hex16(&bytes[24..40])?);
    let flags = hex(&bytes[40..42])?;
    if flags > 0b11 || bytes[42] != b'|' {
        return None;
    }
    // Byte 42 is ASCII, so `HEADER` is a character boundary, as is a `|`.
    let rest = text.get(HEADER..)?;
    let (type_name, public) = if flags & 1 != 0 {
        let name_len = rest.bytes().position(|byte| byte == b'|')?;
        (rest.get(..name_len)?, Some(rest.get(name_len + 1..)?))
    } else {
        (rest, None)
    };
    if type_name.is_empty()
        || type_name.len() > MAX_NAME
        || !type_name
            .bytes()
            .fold(true, |graphic, byte| graphic & byte.is_ascii_graphic())
        || public.is_some_and(|text| text.len() > MAX_PUBLIC)
    {
        return None;
    }
    Some(Identity {
        code,
        severity,
        category,
        kinds,
        has_public: public.is_some(),
        public,
        transparent: flags & 2 != 0,
        type_name,
    })
}

#[cfg(test)]
mod tests {
    use super::{decode, hex, hex16, hex8};
    use crate::{Category, Kinds, Severity};

    /// Every byte value in every position, against the digit-at-a-time form.
    #[test]
    fn test_hex8_agrees_with_hex() {
        for position in 0..8 {
            for byte in 0..=255 {
                let mut chunk = *b"09afc3e1";
                chunk[position] = byte;
                assert_eq!(hex8(&chunk), hex(&chunk), "{chunk:?}");
            }
        }
        assert_eq!(hex8(b"0123abcd"), Some(0x0123_abcd));
        assert_eq!(hex8(b"ffffffff"), Some(0xffff_ffff));
    }

    /// Neighbouring bad bytes cannot hide each other through a carry.
    #[test]
    fn test_hex8_rejects_pairs_of_bad_bytes() {
        for first in (0..=255).step_by(3) {
            for second in 0..=255 {
                let mut chunk = *b"00000000";
                chunk[3] = first;
                chunk[4] = second;
                assert_eq!(hex8(&chunk), hex(&chunk), "{chunk:?}");
            }
        }
    }

    #[test]
    fn test_hex16_reads_the_high_half_first() {
        assert_eq!(hex16(b"0123456789abcdef"), Some(0x0123_4567_89ab_cdef));
        assert_eq!(hex16(b"0123456789abcde"), None);
    }

    #[test]
    fn test_decode_golden_probes() {
        let id = decode("\0DE13b34a2f2600000011104000000000000000101|DbError::Timeout|Try later.")
            .unwrap();
        assert_eq!(id.code.map(|c| c.number()), Some(1));
        assert_eq!(id.severity, Severity::ERROR);
        assert_eq!(id.category, Category::DeadlineExceeded);
        assert_eq!(id.kinds, Kinds::ERROR);
        assert!(id.has_public && !id.transparent);
        assert_eq!(id.public, Some("Try later."));
        assert_eq!(id.type_name, "DbError::Timeout");

        let plain =
            decode("\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|PageError::NotFound").unwrap();
        assert!(plain.code.is_none());
        assert_eq!(plain.category, Category::Unknown);
        assert_eq!(plain.public, None);
    }

    #[test]
    fn test_decode_rejects_malformed_probes() {
        let good = "\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|T";
        assert!(decode(good).is_some());
        let cases = [
            "",
            "\0DE1",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|",
            "\0DE2xxxxxxxxxxxxxxxx1102000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxg1102000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx0002000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx1900000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx1100000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx1111000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000104|T",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000100:T",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|T T",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|T\n",
            "\0DE1xxxxxxxxxxxxxxxX1102000000000000000100|T",
            "\0DE13b34a2f2610000011102000000000000000100|T",
            "\0DE10000000000000000011102000000000000000100|T",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000101|T",
            "\0DE1xxxxxxxxxxxxxxxx1102000000000000000101||text",
        ];
        for case in cases {
            assert!(decode(case).is_none(), "{case:?}");
        }
    }

    #[test]
    fn test_decode_name_length_limit() {
        let mut probe = std::string::String::from("\0DE1xxxxxxxxxxxxxxxx1102000000000000000100|");
        probe.push_str(&"N".repeat(128));
        assert!(decode(&probe).is_some());
        probe.push('N');
        assert!(decode(&probe).is_none());
    }

    #[test]
    fn test_decode_public_length_limit() {
        let mut probe = std::string::String::from("\0DE1xxxxxxxxxxxxxxxx1102000000000000000101|T|");
        probe.push_str(&"p".repeat(512));
        assert_eq!(decode(&probe).unwrap().public.map(str::len), Some(512));
        probe.push('p');
        assert!(decode(&probe).is_none());
    }

    extern crate std;
}
